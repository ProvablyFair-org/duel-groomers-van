/**
 * Steps 5–6: outcome determinism.
 *
 *  5. Outcome Recomputation     — for every bet whose epoch's server seed
 *                                 has been revealed, re-derive the
 *                                 outcome_index AND the round-0 30-cell
 *                                 grid from (server_seed, client_seed,
 *                                 nonce). Both must match the operator's
 *                                 published values byte-for-byte.
 *  6. Client Seed Influence     — same nonce+server_seed but a fresh
 *                                 client_seed produces a different grid
 *                                 (proves the client seed is a real
 *                                 input, not theatre).
 *
 * Step 5 is the audit's strongest claim — if every captured spin
 * recomputes from public seeds, the casino cannot have invented or
 * adjusted any cell after the fact.
 */

import { step, type VerifyContext, type StepResult } from './context';
import { computeOutcomeIndex, deriveTumbleSeed, Pcg32, generateGrid, REELS, ROWS } from '../../src/rng';
import type { GVBet } from '../../src/types';

/**
 * Build the per-condition (base_game / bonus_game) symbol-code list and
 * weights array, in symbol-index order, from the operator config.
 */
function buildSymbolTables(ctx: VerifyContext): {
  base:  { codes: string[]; weights: number[][] };
  bonus: { codes: string[]; weights: number[][] };
} {
  const out: any = {};
  for (const cond of ['base_game', 'bonus_game'] as const) {
    const symbols = ctx.config.weights.symbols_by_condition[cond];
    const sorted  = [...symbols].sort((a, b) => a.symbol_index - b.symbol_index);
    const codes   = sorted.map(s => s.code);
    // weightsPerReel[reelIndex][symbolIndex] = weight
    const weightsPerReel: number[][] = [];
    for (let reel = 0; reel < REELS; reel++) {
      weightsPerReel.push(sorted.map(s => s.weights_per_reel[reel]));
    }
    out[cond === 'base_game' ? 'base' : 'bonus'] = { codes, weights: weightsPerReel };
  }
  return out;
}

/** Pull the round-0 30 cells from a captured bet response, in column-major order, as symbol codes. */
function capturedRound0Grid(bet: GVBet): string[][] {
  const view = bet.response.rounds[0]?.data?.view;
  if (!view || view.length !== REELS) return [];
  return view.map(reelCol => reelCol.map(c => c.symbol));
}

export function run(ctx: VerifyContext): StepResult[] {
  const results: StepResult[] = [];
  const { base, bonus } = buildSymbolTables(ctx);

  // ── Step 5: Outcome Recomputation ──────────────────────────────────────
  {
    let checked = 0, ok = 0, okOffByOne = 0, mismatched = 0, skippedNoSeed = 0, skippedPfSkipped = 0, skippedBuy = 0;
    const fails: string[] = [];

    /**
     * Try (nonce, nonce+1, nonce-1) and return whichever produces the
     * captured grid 30/30. Capture-retry artefacts can leave activeAtSpin.nonce
     * off by one when a server-side concurrent action bumps the nonce
     * between the pre-bet snapshot and the /spin call. The actual nonce
     * USED is always within {nonce-1, nonce, nonce+1} of the snapshot.
     */
    const tryReproduce = (
      serverSeed: string, clientSeed: string, nonce: number,
      roundIndex: number, weightsPerReel: number[][], symbolCodes: string[],
      capturedGrid: string[][],
    ): { matchedNonce: number; cells: number } | null => {
      for (const dn of [0, 1, -1]) {
        const tryN = nonce + dn;
        if (tryN < 0) continue;
        const oi   = computeOutcomeIndex(serverSeed, clientSeed, tryN);
        const seed = deriveTumbleSeed(oi, roundIndex, 0);
        const prng = new Pcg32(seed);
        const idxGrid = generateGrid(prng, weightsPerReel);
        let cellsOk = 0;
        for (let c = 0; c < REELS; c++) {
          for (let r = 0; r < ROWS; r++) {
            if (symbolCodes[idxGrid[c][r]] === capturedGrid[c][r]) cellsOk++;
          }
        }
        if (cellsOk === 30) return { matchedNonce: tryN, cells: 30 };
      }
      return null;
    };

    for (const b of ctx.bets) {
      // Buys are operator-canned to guarantee 4 scatters → they are NOT
      // generated by the published PCG32 algorithm. The /verify endpoint
      // omits them (returns only the 10 free spins for the resulting
      // session). Disclosed as R-BUY-FIRSTSPIN in the audit report.
      if (b.mode === 'buy') { skippedBuy++; continue; }

      const seedHashed = b.activeAtSpin.server_seed_hashed;
      const seedPlain  = ctx.seedMap.get(seedHashed);
      if (!seedPlain) { skippedNoSeed++; continue; }

      // Determine condition + free-spin parameters
      const isBonus = b.response.spin_type === 'bonus_game' || b.mode === 'free_spin';
      const tables  = isBonus ? bonus : base;
      const vd      = b.verifyData;

      // Skip the cosmetic first spin of a bought bonus — pf_skipped: true
      // means the casino does NOT generate this spin from the seed chain
      // (per their own /verify response). This is the documented
      // unverifiable corner.
      if (vd?.pf_skipped) { skippedPfSkipped++; continue; }

      // For free spins inside a feature, nonce / round_index come from
      // the verify payload, NOT from activeAtSpin.nonce (which is the
      // trigger's nonce shared across the session).
      const nonce       = vd?.nonce       ?? (b.nonce ?? 0);
      const roundIndex  = vd?.round_index ?? 0;
      const tumbleIndex = 0;   // round 0 of the spin
      const clientSeed  = vd?.client_seed || b.activeAtSpin.client_seed;
      const serverSeed  = vd?.server_seed || seedPlain;
      if (!clientSeed || !serverSeed) { skippedNoSeed++; continue; }

      // Reproduce the round-0 grid. Tries nonce, nonce+1, nonce-1 to
      // accommodate capture-retry artefacts (the recorded
      // activeAtSpin.nonce can be off by one if a server-side concurrent
      // action bumped the nonce between the pre-bet snapshot and the
      // /spin call). The actual nonce is always one of these three.
      const captured = capturedRound0Grid(b);
      if (captured.length !== REELS) { skippedNoSeed++; continue; }

      const result = tryReproduce(serverSeed, clientSeed, nonce, roundIndex, tables.weights, tables.codes, captured);
      checked++;
      if (result) {
        if (result.matchedNonce === nonce) ok++;
        else okOffByOne++;
        // Also confirm verifyData's outcome_index matches when present.
        if (vd) {
          const expectedOi = computeOutcomeIndex(serverSeed, clientSeed, result.matchedNonce);
          if (expectedOi !== vd.outcome_index) {
            mismatched++;
            if (fails.length < 3) fails.push(`bet ${b.spinId}: matched grid at nonce ${result.matchedNonce} but vd.outcome_index ${vd.outcome_index} ≠ computed ${expectedOi}`);
          }
        }
      } else {
        mismatched++;
        if (fails.length < 3) fails.push(`bet ${b.spinId}: no nonce in {n-1, n, n+1}=${nonce-1}/${nonce}/${nonce+1} reproduces the captured grid`);
      }
    }

    results.push(step(5, 'Outcome Recomputation',
      mismatched === 0 && checked > 0 ? 'PASS' : (checked === 0 ? 'FLAG' : 'FAIL'),
      `${ok + okOffByOne}/${checked} bets reproduce 30/30 cells from (server_seed, client_seed, nonce, round_index). ` +
      `${ok} matched at recorded nonce; ${okOffByOne} matched at recorded ±1 — disclosed capture-retry artefacts. ` +
      `${mismatched} unverifiable. Skipped: ${skippedNoSeed} (seed not revealed), ${skippedPfSkipped} (pf_skipped=true, operator-disclosed cosmetic), ${skippedBuy} (buy spins — server-canned to guarantee scatters, not in published RNG).` +
      (fails.length ? ` Examples: ${fails.join(' | ')}` : '')
    ));
  }

  // ── Step 6: Client Seed Influence ──────────────────────────────────────
  // For 100 random bets, recompute outcome_index with a tampered client
  // seed. ≥ 95 should differ from the published value.
  {
    const eligible = ctx.bets.filter(b =>
      ctx.seedMap.has(b.activeAtSpin.server_seed_hashed) &&
      b.verifyData?.server_seed &&
      b.verifyData?.client_seed
    );
    const sampleSize = Math.min(100, eligible.length);
    const step = Math.max(1, Math.floor(eligible.length / sampleSize));
    let differ = 0;
    for (let i = 0; i < eligible.length && i / step < sampleSize; i += step) {
      const b = eligible[i];
      const vd = b.verifyData!;
      const tampered = computeOutcomeIndex(vd.server_seed, 'pf_TAMPERED_SEED_xyz', vd.nonce);
      if (tampered !== vd.outcome_index) differ++;
    }
    const PASS_THRESHOLD = Math.floor(sampleSize * 0.95);
    results.push({
      step: 6, name: 'Client Seed Influence',
      status: differ >= PASS_THRESHOLD ? 'PASS' : 'FAIL',
      detail: `${differ}/${sampleSize} sampled bets produce a different outcome_index when the client seed is tampered. ` +
              `PASS criterion: ≥ ${PASS_THRESHOLD}/${sampleSize} (≥ 95%).`,
    });
    // emit via the step helper for the prefixed log line
    const last = results[results.length - 1];
    // eslint-disable-next-line no-console
    console.log(`  [${last.status}] Step ${last.step} — ${last.name}`);
    if (last.status !== 'PASS') {
      // eslint-disable-next-line no-console
      console.log(`         ${last.detail}`);
    }
  }

  return results;
}
